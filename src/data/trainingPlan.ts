import type { StationId } from './profile'

export type SessionType = 'run' | 'strength' | 'compromised' | 'sim' | 'rest'
export type Phase = 'aerobic' | 'build' | 'peak' | 'race'
export type WorkoutType = 'engine' | 'foundation' | 'complete' | 'aerobic' | 'power'

export interface TrainingSession {
  type: SessionType
  workoutType?: WorkoutType
  format?: string            // e.g. "5 RFT", "For Time", "E2MOM × 10", "6 × 800m"
  title: string
  duration: string
  detail: string
  notes: string
  stations?: StationId[]
}

export interface TrainingDay {
  day: string
  session: TrainingSession
}

export interface TrainingWeek {
  week: number
  phase: Phase
  weekTheme: string          // e.g. 'BASE', 'PACE', 'ACCELERATE', 'PRIME'
  title: string
  focus: string
  days: TrainingDay[]
}

